import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import pkg from '../package.json' with { type: 'json' };

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  entryPoints: [resolve(root, 'apps/mcp-probe-app.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  minify: true,
  write: false,
  define: {
    '__MCP_PROBE_VERSION__': JSON.stringify(pkg.version),
  },
});
const js = result.outputFiles?.[0]?.text;
if (!js) throw new Error('MCP Apps bundle was not generated');
const out = resolve(root, 'src/resources/generated/mcp-app-bundle.ts');
await mkdir(dirname(out), { recursive: true });
await writeFile(out, `// Generated by scripts/build-mcp-apps.mjs\nexport const MCP_APP_BUNDLE = ${JSON.stringify(js)};\n`, 'utf8');
console.log(`[build-mcp-apps] ${js.length} bytes -> ${out}`);
