/** Compile the single-project workbench from maintainable sources. */
import { transform } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root=resolve(import.meta.dirname,'../src/devcontrol/workbench');
const source=readFileSync(resolve(root,'page.html'),'utf8');
// Derived from docs/assets/logo.png (official mcp-probe-kit mark), small
// offline-optimized WebP; inline so local CSP/no-network mode still renders.
const brandMark='data:image/webp;base64,'+
  readFileSync(resolve(root,'brand-mark.webp')).toString('base64');
const style=readFileSync(resolve(root,'styles.css'),'utf8')+'\n'+
  readFileSync(resolve(root,'light.css'),'utf8')+'\n'+
  readFileSync(resolve(root,'overview.css'),'utf8')+'\n'+
  readFileSync(resolve(root,'clarity.css'),'utf8');
const css=await transform(style,{loader:'css',minify:true,target:'es2020'});
const router=readFileSync(resolve(root,'router.js'),'utf8').replace('export function createHashRouter',
  'function createHashRouter');
const fragments=['app.js','guide.js','state.js','tasks.js','records.js','features.js',
  'markdown.js','documents.js','runtime.js'];
const app=fragments.map(name=>readFileSync(resolve(root,name),'utf8')).join('\n')
  .replace("import { createHashRouter } from './router.js';\n",'');
// Keep the original renderer functions' whitespace intact: executable
// acceptance tests inspect the precise browser functions, not a duplicate.
// The only cross-module dependency is the native router, which is compiled
// into the same inline script (single request, CSP nonce, no loader).
const browserJS='"use strict";\n'+router+'\n'+app;
await transform(browserJS,{loader:'js',target:'es2020'}); // Compile-time syntax check.
if(!source.includes('__STYLES__')||!source.includes('__SCRIPT__'))
  throw Error('Workbench asset template incomplete');
const output='/** Generated by scripts/build-workbench.mjs; edit workbench sources, not this. */\n'
  +'export const workbenchMarkup = '+JSON.stringify(source.replaceAll('__BRAND_MARK__',brandMark))+';\n'
  +'export const workbenchCSS = '+JSON.stringify(css.code)+';\n'
  +'export const workbenchJS = '+JSON.stringify(browserJS)+';\n';
const path=resolve(root,'generated.ts');
writeFileSync(path,output,'utf8');
console.log('[workbench] compiled HTML '+source.length+' B, CSS '+css.code.length+' B, JS '+browserJS.length+' B; zero added runtime dependencies');
